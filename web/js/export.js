// export.js - ready-to-use code for the trained gains: a C function with the simulator's exact arithmetic
// (sim/rt_engine.hpp Pid::Control = upstream PidController.hpp) and the firmware config defines.
export function cFunction(robot, g) {
  const f = (x) => (+x).toPrecision(6) + 'f';
  const p = robot.pid;
  return `// pid_gains.h - generated by Robot Tuner for "${robot.name}"
// Same arithmetic as the simulator (Robot Tuner sim/rt_engine.hpp Pid::Control = upstream PidController.hpp).
// Call pid_control() once per control tick with the two side distances (metres) and the measured tick time.
#pragma once
#include <math.h>

#define PID_KP              ${f(g.kp)}   // (m/s of turn) per metre of error
#define PID_KI              ${f(g.ki)}   // (m/s of turn) per metre*second
#define PID_KD              ${f(g.kd)}   // (m/s of turn) per metre/second
#define PID_MAX_SPEED_MPS   ${f(robot.motor.max_speed_mps)}   // wheel speed limit (measured top speed)
#define PID_BASE_SPEED_FRAC ${f(g.speed)}   // cruise speed = ${(g.speed * robot.motor.max_speed_mps).toFixed(3)} m/s
#define PID_ERROR_CLIP_M    ${f(p.error_clip_mm / 1000)}
#define PID_INTEGRAL_LIMIT  ${f(p.integral_limit)}
#define PID_D_FILTER_ALPHA  ${f(p.d_filter_alpha)}   // per 50 ms
#define PID_SLOWDOWN_FRAC   ${f(p.slowdown_frac)}

typedef struct { float integral, prev_err, d_filtered; int has_prev; } pid_state_t;

static inline float pid_clampf(float x, float lo, float hi) { return x < lo ? lo : (x > hi ? hi : x); }
static inline void pid_reset(pid_state_t* s) { s->integral = 0; s->prev_err = 0; s->d_filtered = 0; s->has_prev = 0; }

// left_m / right_m: distances of the left- and right-looking sensors. dt: seconds since the last call.
// Outputs: wheel speed targets in m/s (give them to your wheel speed controller).
static inline void pid_control(pid_state_t* s, float left_m, float right_m, float dt, float* v_left, float* v_right) {
    const float max_v = PID_MAX_SPEED_MPS;
    float err = pid_clampf(left_m - right_m, -PID_ERROR_CLIP_M, PID_ERROR_CLIP_M);    // + = more room on the left
    s->integral = pid_clampf(s->integral + err * dt, -PID_INTEGRAL_LIMIT, PID_INTEGRAL_LIMIT);
    float raw_d = s->has_prev ? (err - s->prev_err) / dt : 0.0f;
    float alpha = 1.0f - powf(1.0f - PID_D_FILTER_ALPHA, dt / 0.05f);
    s->d_filtered = alpha * raw_d + (1.0f - alpha) * s->d_filtered;
    s->prev_err = err; s->has_prev = 1;
    float turn = pid_clampf(PID_KP * err + PID_KI * s->integral + PID_KD * s->d_filtered, -max_v, max_v);
    float base = PID_BASE_SPEED_FRAC * max_v * (1.0f - PID_SLOWDOWN_FRAC * fabsf(turn) / max_v);
    *v_left  = pid_clampf(base - turn, -max_v, max_v);
    *v_right = pid_clampf(base + turn, -max_v, max_v);
}
`;
}
export function configH(robot, g) {
  const f = (x) => (+x).toPrecision(6) + 'f';
  return `// Paste into firmware/robot_fw*/model_defaults.h (Simulation-To-Real-Life firmware), replacing the DEF_PID_* lines.
// Trained by Robot Tuner for "${robot.name}". Saved NVS values on the robot override these (SET / SAVE).
#define DEF_PID_KP                       ${f(g.kp)}
#define DEF_PID_KI                       ${f(g.ki)}
#define DEF_PID_KD                       ${f(g.kd)}
#define DEF_PID_BASE_SPEED_FRAC          ${f(g.speed)}
#define DEF_PID_ERROR_CLIP_M             ${f(robot.pid.error_clip_mm / 1000)}
#define DEF_PID_INTEGRAL_LIMIT           ${f(robot.pid.integral_limit)}
#define DEF_PID_D_FILTER_ALPHA           ${f(robot.pid.d_filter_alpha)}
#define DEF_PID_SLOWDOWN_FRAC            ${f(robot.pid.slowdown_frac)}
`;
}
export function modelTxt(robot, g) {
  return `controller pid\nkp ${g.kp}\nki ${g.ki}\nkd ${g.kd}\nbase_speed_frac ${g.speed}\nerror_clip_m ${robot.pid.error_clip_mm / 1000}\ntrack_width ${(robot.wheels.track_effective_mm / 1000).toFixed(4)}\n`;
}
