// export.js - ready-to-use code for the trained gains: a C function with the simulator's exact arithmetic
// (sim/rt_engine.hpp Pid::Control = upstream PidController.hpp in its constant-speed mode, const_speed) and the
// firmware config defines.
import { cruiseSpeed } from './store.js';

const vminOf = (robot) => Math.min(Math.max(0, robot.motor.v_min_mps || 0), robot.motor.max_speed_mps);

/** g = {kp, ki, kd, speed (= speed_frac)} */
export function cFunction(robot, g) {
  const f = (x) => (+x).toPrecision(6) + 'f';
  const p = robot.pid;
  return `// pid_gains.h - generated by Robot Tuner for "${robot.name}"
// Same arithmetic as the simulator (Robot Tuner sim/rt_engine.hpp Pid::Control, constant cruise speed):
//   e = clamp(left - right, +-error_clip); integral = clamp(integral + e dt, +-integral_limit)
//   d_filt = alpha d_raw + (1 - alpha) d_filt; turn = clamp(Kp e + Ki integral + Kd d_filt, +-v_max)
//   base = v_min + speed_frac (v_max - v_min)   (constant: no slowdown)
//   v_left = base - turn, v_right = base + turn, each clamped to +-v_max
// Call pid_control() once per control tick with the two side distances (metres) and the measured tick time.
#pragma once
#include <math.h>

#define PID_KP              ${f(g.kp)}   // (m/s of turn) per metre of error
#define PID_KI              ${f(g.ki)}   // (m/s of turn) per metre*second
#define PID_KD              ${f(g.kd)}   // (m/s of turn) per metre/second
#define PID_V_MAX_MPS       ${f(robot.motor.max_speed_mps)}   // wheel speed limit (measured top speed)
#define PID_V_MIN_MPS       ${f(vminOf(robot))}   // slowest steady wheel speed (Measure: slowest speed)
#define PID_SPEED_FRAC      ${f(g.speed)}   // cruise = ${cruiseSpeed(robot, g.speed).toFixed(3)} m/s
#define PID_ERROR_CLIP_M    ${f(p.error_clip_mm / 1000)}
#define PID_INTEGRAL_LIMIT  ${f(p.integral_limit)}
#define PID_D_FILTER_ALPHA  ${f(p.d_filter_alpha)}   // per 50 ms
// Drive this far LEFT of the centre (m, negative = right). Parallel and o m off-centre, a sensor at angle a sees
// its wall o/sin(a) nearer or farther, so the wanted left - right is -o (1/sin a_left + 1/sin a_right).
#define PID_OFFSET_M        ${f((p.offset_mm || 0) / 1000)}
#define PID_SIN_LEFT        ${f(Math.abs(Math.sin(Math.max(...robot.sensors.map((q) => q.angle_deg)) * Math.PI / 180)))}   // sin of the left sensor's angle
#define PID_SIN_RIGHT       ${f(Math.abs(Math.sin(Math.min(...robot.sensors.map((q) => q.angle_deg)) * Math.PI / 180)))}   // sin of the right sensor's angle

typedef struct { float integral, prev_err, d_filtered; int has_prev; } pid_state_t;

static inline float pid_clampf(float x, float lo, float hi) { return x < lo ? lo : (x > hi ? hi : x); }
static inline void pid_reset(pid_state_t* s) { s->integral = 0; s->prev_err = 0; s->d_filtered = 0; s->has_prev = 0; }

// left_m / right_m: distances of the left- and right-looking sensors. dt: seconds since the last call.
// Outputs: wheel speed targets in m/s (give them to your wheel speed controller).
static inline void pid_control(pid_state_t* s, float left_m, float right_m, float dt, float* v_left, float* v_right) {
    const float max_v = PID_V_MAX_MPS;
    const float setpoint = -PID_OFFSET_M * (1.0f / PID_SIN_LEFT + 1.0f / PID_SIN_RIGHT);  // 0 when centred
    float err = pid_clampf(left_m - right_m - setpoint, -PID_ERROR_CLIP_M, PID_ERROR_CLIP_M);  // + = turn left
    s->integral = pid_clampf(s->integral + err * dt, -PID_INTEGRAL_LIMIT, PID_INTEGRAL_LIMIT);
    float raw_d = s->has_prev ? (err - s->prev_err) / dt : 0.0f;
    float alpha = 1.0f - powf(1.0f - PID_D_FILTER_ALPHA, dt / 0.05f);
    s->d_filtered = alpha * raw_d + (1.0f - alpha) * s->d_filtered;
    s->prev_err = err; s->has_prev = 1;
    float turn = pid_clampf(PID_KP * err + PID_KI * s->integral + PID_KD * s->d_filtered, -max_v, max_v);
    float base = PID_V_MIN_MPS + PID_SPEED_FRAC * (max_v - PID_V_MIN_MPS);
    *v_left  = pid_clampf(base - turn, -max_v, max_v);
    *v_right = pid_clampf(base + turn, -max_v, max_v);
}
`;
}
/** Defines for the Simulation-To-Real-Life firmware (model_defaults.h). Its PID has no constant-speed mode yet: with
 *  slowdown 0 its base is base_speed_frac x max_v, i.e. the same constant cruise speed. */
export function configH(robot, g) {
  const f = (x) => (+x).toPrecision(6) + 'f';
  const vmax = robot.motor.max_speed_mps, base = cruiseSpeed(robot, g.speed);
  return `// Paste into firmware/robot_fw*/model_defaults.h (Simulation-To-Real-Life firmware), replacing the DEF_PID_* lines.
// Trained by Robot Tuner for "${robot.name}". Saved NVS values on the robot override these (SET / SAVE).
// Constant cruise speed: base = v_min + speed_frac (v_max - v_min) = ${base.toFixed(4)} m/s (simulator: cs_mode 1).
// The firmware has no constant-speed mode yet: BASE_SPEED_FRAC = base / v_max with SLOWDOWN_FRAC 0 gives the same
// constant cruise speed there. For the simulator (PID/sim_config.txt): ${simConfigLines(robot, g).trim().split('\n').join(', ')}
#define DEF_PID_KP                       ${f(g.kp)}
#define DEF_PID_KI                       ${f(g.ki)}
#define DEF_PID_KD                       ${f(g.kd)}
#define DEF_PID_SPEED_FRAC               ${f(g.speed)}
#define DEF_PID_V_MIN                    ${f(vminOf(robot))}
#define DEF_PID_BASE_SPEED_FRAC          ${f(base / vmax)}
#define DEF_PID_SLOWDOWN_FRAC            ${f(0)}
#define DEF_PID_ERROR_CLIP_M             ${f(robot.pid.error_clip_mm / 1000)}
#define DEF_PID_INTEGRAL_LIMIT           ${f(robot.pid.integral_limit)}
#define DEF_PID_D_FILTER_ALPHA           ${f(robot.pid.d_filter_alpha)}
`;
}
/** Upstream model file (PID/PidController.hpp Load): "const_speed 1" switches on the constant-speed mode. Its
 *  speed_frac and v_min are SimConfig keys (cs_speed_frac, cs_v_min_mps): see simConfigLines(). v_min is NOT a model
 *  key there (a v_min key switches on the JOB 10 speed law). */
export function modelTxt(robot, g) {
  return `controller pid\nkp ${g.kp}\nki ${g.ki}\nkd ${g.kd}\nbase_speed_frac ${g.speed}\nconst_speed 1\nerror_clip_m ${robot.pid.error_clip_mm / 1000}\ntrack_width ${(robot.wheels.track_effective_mm / 1000).toFixed(4)}\n`;
}
/** Lines for upstream PID/sim_config.txt (or pid_params.txt): the constant-speed settings. */
export function simConfigLines(robot, g) {
  return `cs_mode 1\ncs_speed_frac ${g.speed}\ncs_v_min_mps ${+vminOf(robot).toPrecision(6)}\n`;
}
